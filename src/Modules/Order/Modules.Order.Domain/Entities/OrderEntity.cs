using Ardalis.Result;
using Modules.Order.Domain.Enums;
using SharedKernel.Base;
using System.Transactions;

namespace Modules.Order.Domain.Entities;

public sealed class OrderEntity : BaseEntityIdentity
{
    private OrderEntity()
    {
    }

    public long ShoppingCartId { get; private set; }
    public decimal TotalAmount { get; private set; }
    public OrderStatus OrderStatus { get; private set; } = OrderStatus.PendingPayment;
    public decimal TaxAmount { get; private set; }
    public bool TermsAccepted { get; private set; }
    public long? ShippingAddressId { get; private set; }
    public string? ShippingRecipientName { get; private set; }
    public string? ShippingProvince { get; private set; }
    public string? ShippingCity { get; private set; }
    public string? ShippingPostalCode { get; private set; }
    public string? ShippingAddress { get; private set; }
    public string? MobileNumber { get; private set; }
    public string? TrackingNumber { get; private set; }
    public DateTime CreatedAt { get; private set; }

    // Navigation properties
    public ShoppingCart ShoppingCart { get; private set; }
    public ICollection<OrderItem> OrderItems { get; set; } = [];
    public ICollection<OrderTransaction> Transactions { get; private set; } = [];

    private OrderEntity(
        long id,
        long shoppingCartId,
        decimal totalAmount,
        OrderStatus orderStatus,
        decimal taxAmount,
        bool termsAccepted,
        string? shippingAddress,
        string? mobileNumber,
        string? trackingNumber,
        DateTime createdAt
    )
    {
        Id = id;
        ShoppingCartId = shoppingCartId;
        TotalAmount = totalAmount;
        OrderStatus = orderStatus;
        TaxAmount = taxAmount;
        TermsAccepted = termsAccepted;
        ShippingAddress = shippingAddress;
        MobileNumber = mobileNumber;
        TrackingNumber = trackingNumber;
        CreatedAt = createdAt;
    }


    public OrderTransaction CreatePaymentTransaction()
    {
        if (OrderStatus == OrderStatus.Paid)
            throw new InvalidOperationException("Order is already paid.");

        var transaction = new OrderTransaction(Id, TotalAmount);

        Transactions.Add(transaction);

        return transaction;
    }

    public static Result<OrderEntity> Create(
        long shoppingCartId,
        string? shippingAddress = null,
        string? mobileNumber = null,
        string? trackingNumber = null
    )
    {
        if (shoppingCartId <= 0)
            return Result.Invalid(new ValidationError
                { Identifier = nameof(shoppingCartId), ErrorMessage = "Shopping cart ID must be greater than zero" });

        return Result.Success(new OrderEntity(
            0, // Id will be generated by database
            shoppingCartId,
            0,
            OrderStatus.PendingPayment,
            0,
            false,
            shippingAddress,
            mobileNumber,
            trackingNumber,
            DateTime.UtcNow
        ));
    }

    public Result UpdateTrackingNumber(string trackingNumber)
    {
        if (OrderStatus != OrderStatus.PendingPayment)
            return Result.Invalid(new ValidationError
            {
                Identifier = nameof(TrackingNumber),
                ErrorMessage = "Order must be in Pending status to update tracking number"
            });

        if (string.IsNullOrWhiteSpace(trackingNumber))
            return Result.Invalid(new ValidationError
                { Identifier = nameof(trackingNumber), ErrorMessage = "Tracking number cannot be empty" });

        TrackingNumber = trackingNumber;
        return Result.Success();
    }

    public Result UpdateShippingAddress(
        long addressId,
        string recipientName,
        string province,
        string city,
        string postalCode,
        string addressLine,
        string mobileNumber)
    {
        if (OrderStatus != OrderStatus.PendingPayment)
            return Result.Invalid(new ValidationError
            {
                Identifier = nameof(OrderStatus),
                ErrorMessage = "Only pending orders can update the shipping address"
            });

        if (addressId <= 0)
            return Result.Invalid(new ValidationError
            {
                Identifier = nameof(addressId),
                ErrorMessage = "Address ID must be greater than zero"
            });

        if (string.IsNullOrWhiteSpace(recipientName) ||
            string.IsNullOrWhiteSpace(province) ||
            string.IsNullOrWhiteSpace(city) ||
            string.IsNullOrWhiteSpace(postalCode) ||
            string.IsNullOrWhiteSpace(addressLine) ||
            string.IsNullOrWhiteSpace(mobileNumber))
            return Result.Invalid(new ValidationError
            {
                Identifier = nameof(addressLine),
                ErrorMessage = "Shipping address details cannot be empty"
            });

        ShippingAddressId = addressId;
        ShippingRecipientName = recipientName;
        ShippingProvince = province;
        ShippingCity = city;
        ShippingPostalCode = postalCode;
        ShippingAddress = addressLine;
        MobileNumber = mobileNumber;

        return Result.Success();
    }

    public Result UpdateStatus(OrderStatus newStatus)
    {
        if (newStatus == OrderStatus.PendingPayment && OrderStatus != OrderStatus.PendingPayment)
            return Result.Invalid(new ValidationError
                { Identifier = nameof(OrderStatus), ErrorMessage = "Cannot set status to Pending" });

        OrderStatus = newStatus;
        return Result.Success();
    }

    public Result AddOrderItem(OrderItem orderItem)
    {
        if (orderItem == null)
            return Result.Invalid(new ValidationError
                { Identifier = nameof(orderItem), ErrorMessage = "Order item cannot be null" });

        if (OrderStatus != OrderStatus.PendingPayment)
            return Result.Invalid(new ValidationError
                { Identifier = nameof(OrderStatus), ErrorMessage = "Order must be in Pending status to add items" });

        OrderItems.Add(orderItem);
        TotalAmount += orderItem.TotalPrice;
        return Result.Success();
    }

    public Result RemoveOrderItem(OrderItem orderItem)
    {
        if (orderItem == null)
            return Result.Invalid(new ValidationError
                { Identifier = nameof(orderItem), ErrorMessage = "Order item cannot be null" });

        if (OrderStatus != OrderStatus.PendingPayment)
            return Result.Invalid(new ValidationError
                { Identifier = nameof(OrderStatus), ErrorMessage = "Order must be in Pending status to remove items" });

        OrderItems.Remove(orderItem);
        TotalAmount -= orderItem.TotalPrice;
        return Result.Success();
    }

    public Result UpdateOrderItem(OrderItem orderItem, decimal newQuantity)
    {
        if (orderItem == null)
            return Result.Invalid(new ValidationError
                { Identifier = nameof(orderItem), ErrorMessage = "Order item cannot be null" });

        if (OrderStatus != OrderStatus.PendingPayment)
            return Result.Invalid(new ValidationError
                { Identifier = nameof(OrderStatus), ErrorMessage = "Order must be in Pending status to update items" });

        var oldPrice = orderItem.TotalPrice;
        var quantityResult = orderItem.UpdateQuantity(newQuantity);
        if (!quantityResult.IsSuccess)
            return quantityResult;

        TotalAmount = TotalAmount - oldPrice + orderItem.TotalPrice;
        return Result.Success();
    }

    public Result MarkPaid()
    {
        if (OrderStatus == OrderStatus.Paid)
            return Result.Success();

        if (OrderStatus != OrderStatus.PendingPayment)
            return Result.Conflict("Only pending payment orders can be paid.");

        OrderStatus = OrderStatus.Paid;
        return Result.Success();
    }

    public void MarkPaymentFailed()
    {
        if (OrderStatus == OrderStatus.Paid)
            return;

        OrderStatus = OrderStatus.PendingPayment;
    }

    public Result UpdateTotalAmount(decimal newAmount)
    {
        if (newAmount < 0)
            return Result.Invalid(new ValidationError
                { Identifier = nameof(newAmount), ErrorMessage = "Total amount cannot be negative" });

        TotalAmount = newAmount;
        return Result.Success();
    }

    public Result ChangeCart(long shoppingCartId)
    {
        if (shoppingCartId <= 0)
            return Result.Invalid(new ValidationError
            {
                Identifier = nameof(shoppingCartId),
                ErrorMessage = "Shopping cart ID must be greater than zero"
            });

        if (OrderStatus != OrderStatus.PendingPayment)
            return Result.Invalid(new ValidationError
            {
                Identifier = nameof(OrderStatus),
                ErrorMessage = "Only pending orders can be moved"
            });

        ShoppingCartId = shoppingCartId;
        return Result.Success();
    }

    public Result TransferCart(long shoppingCartId)
    {
        if (shoppingCartId <= 0)
            return Result.Invalid(new ValidationError
            {
                Identifier = nameof(shoppingCartId),
                ErrorMessage = "Shopping cart ID must be greater than zero"
            });

        ShoppingCartId = shoppingCartId;
        return Result.Success();
    }
}